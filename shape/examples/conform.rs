//! The shaper's conformance harness: every string shaped twice, once by the
//! GPU shaper and once by **harfrust**, and every glyph id and every position compared in font units
//! with a tolerance of zero.
//!
//! ```text
//! cargo run -p punchcutter-shape --example conform
//! ```
//!
//! On a machine with a discrete GPU, prefix it with the integrated GPU's
//! driver, `VK_DRIVER_FILES=/usr/share/vulkan/icd.d/radeon_icd.x86_64.json`
//! (or `intel_icd`), so the discrete one is never opened.
//!
//! Headless: no surface, no window. One compute pass over the corpus
//! per (font, size), the results read back, and a line per mismatch. The exit
//! status is the gate.
//!
//! **The iGPU, always.** The adapter is chosen by `device_type ==
//! IntegratedGpu` and refused if its name says NVIDIA: waking a discrete GPU to
//! measure a few hundred strings is the one failure this harness must not
//! commit. A CPU adapter (lavapipe) is taken too, which is what lets this run
//! on a machine with no GPU at all.
//!
//! # Why the tolerance is zero
//!
//! Why harfrust and not a text library: a library that compares in pixels, within 1/64, would cost two honest differences to forgive. One splits a line into words before it shapes, so a GSUB context spanning a space cannot fire there, and it reaches
//! for a fallback font this side has no id for.
//!
//! So this compares against harfrust directly, whole string, same font bytes, same
//! (absent) features, at a pixel size equal to the face's `unitsPerEm` — so the
//! shader's 26.6 output is exactly 64 × the font units it accumulated, and the
//! comparison is between integers. There is nothing to forgive and nothing to
//! round. A mismatch is a bug.
//!
//! # Two corpora
//!
//! **A user interface's** — clock strings, menu rows, settings labels, the
//! ligatures and kerning pairs that break shapers — at three pixel sizes, to
//! prove the 26.6 conversion as well as the layout. **HarfBuzz's**: the
//! `.tests` files harfrust itself is generated from, fetched from
//! <https://github.com/harfbuzz/harfbuzz> into
//! `$XDG_CACHE_HOME/punchcutter/harfrust/hb-tests` (not
//! committed — the fonts carry three licences and are test fixtures, not ours
//! to ship), restricted to the cases the *default shaper* handles and whose
//! options do not change what a shaper does. Every skip is named and counted.
//!
//! The oracle is checked against the corpus too, where a file names its glyphs
//! by id: harfrust's own `tests/shaping/*.rs` are generated by running
//! `hb-shape` over these same files, so a disagreement there is the corpus
//! having moved past harfrust 0.12.0 rather than a failure of the shader.
//!
//! `--ui-only` runs the first corpus alone and `--tests-only` the second.


/// One glyph as harfrust sees it, in font units.
struct RefGlyph {
    gid: u32,
    cluster: u32,
    x_advance: i32,
    x_offset: i32,
    y_offset: i32,
}

/// harfrust, driven the way the shader is: one face, whole string, no
/// features, no variations, **no scale** — so the positions come back in the
/// font's own design units, which is what makes the tolerance zero.
struct Oracle<'a> {
    data: &'a [u8],
    shaper_data: ShaperData,
}

impl<'a> Oracle<'a> {
    fn new(data: &'a [u8]) -> Result<Oracle<'a>> {
        let font = FontRef::new(data).map_err(|err| anyhow::anyhow!("{err:?}"))?;
        Ok(Oracle {
            data,
            shaper_data: ShaperData::new(&font),
        })
    }

    fn shape(&self, text: &str) -> Vec<RefGlyph> {
        self.shape_with(text, &[])
    }

    /// The same, forcing the features a case's `--features` asked for —
    /// the same list the shader is given, spelled in harfrust's own type.
    fn shape_with(&self, text: &str, features: &[Feature]) -> Vec<RefGlyph> {
        if text.is_empty() {
            return Vec::new();
        }
        let font = match FontRef::new(self.data) {
            Ok(font) => font,
            Err(_) => return Vec::new(),
        };
        let forced: Vec<harfrust::Feature> = features
            .iter()
            .map(|f| harfrust::Feature::new(harfrust::Tag::new(&f.tag), u32::from(f.on), ..))
            .collect();
        let shaper = self.shaper_data.shaper(&font).build();
        let mut buffer = UnicodeBuffer::new();
        buffer.push_str(text);
        buffer.guess_segment_properties();
        let output = shaper.shape(buffer, ShapeOptions::new().features(&forced));
        output
            .glyph_infos()
            .iter()
            .zip(output.glyph_positions().iter())
            .map(|(info, pos)| RefGlyph {
                gid: info.glyph_id,
                cluster: info.cluster,
                x_advance: pos.x_advance,
                x_offset: pos.x_offset,
                y_offset: pos.y_offset,
            })
            .collect()
    }
}


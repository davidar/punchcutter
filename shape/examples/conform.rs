/// Where the corpus lives, fetched rather than committed: the fonts carry a
/// dozen licences (Apache 2.0 for aots and text-rendering-tests, harfbuzz's own
/// Old MIT for in-house) and are test fixtures, not ours to ship.
fn corpus_root() -> PathBuf {
    let cache = std::env::var_os("XDG_CACHE_HOME")
        .map(PathBuf::from)
        .unwrap_or_else(|| {
            PathBuf::from(std::env::var_os("HOME").unwrap_or_default()).join(".cache")
        });
    cache.join("punchcutter/harfrust/hb-tests")
}

/// The data directory inside it.
fn corpus_data(root: &Path) -> PathBuf {
    root.join("test/shape/data")
}

/// Fetch the corpus if it is not there. A machine with no network gets a note
/// and the UI corpus alone, which is what lets this run offline.
///
/// The `.tests` files live in **harfbuzz**, not in harfrust: harfrust's own
/// `tests/shaping/*.rs` are generated from them by running `hb-shape` and
/// baking the answer, so the raw corpus has to come from upstream. A sparse,
/// blobless checkout of `test/shape/data` is 13 MB against the repository's
/// several hundred.
fn ensure_corpus() -> Option<PathBuf> {
    let root = corpus_root();
    if corpus_data(&root).is_dir() {
        return Some(root);
    }
    println!();
    println!("fetching HarfBuzz's shaping corpus into {}", root.display());
    if let Some(parent) = root.parent() {
        let _ = std::fs::create_dir_all(parent);
    }
    let run = |args: &[&str], dir: Option<&Path>| -> bool {
        let mut command = std::process::Command::new("git");
        command.args(args);
        if let Some(dir) = dir {
            command.current_dir(dir);
        }
        command.status().map(|s| s.success()).unwrap_or(false)
    };
    let ok = run(
        &[
            "clone",
            "--filter=blob:none",
            "--no-checkout",
            "--depth",
            "1",
            "https://github.com/harfbuzz/harfbuzz",
            &root.to_string_lossy(),
        ],
        None,
    ) && run(&["sparse-checkout", "set", "test/shape/data"], Some(&root))
        && run(&["checkout"], Some(&root));
    if ok && corpus_data(&root).is_dir() {
        Some(root)
    } else {
        println!("the fetch did not complete; the HarfBuzz corpus is skipped");
        let _ = std::fs::remove_dir_all(&root);
        None
    }
}

/// Whether a codepoint belongs to a script the shaper's **placeholder classifier**
/// knows (`scriptTagOf` in `shape.slang`), or to the Common and Inherited
/// characters that take whatever script is around them.
///
/// A codepoint outside both gets the script tag `DFLT` here and its own tag in
/// harfrust, so a font that states its features under, say, `plrd` reaches none
/// of them. That is not a bug in the layout engine; it is the Unicode Script
/// property, which the shader does not have yet. The harness names those cases
/// rather than failing them.
fn classified(ch: char) -> bool {
    let c = ch as u32;
    // Latin, Greek, Cyrillic, CJK and kana: the classifier's own ranges.
    (0x0041..=0x005A).contains(&c)
        || (0x0061..=0x007A).contains(&c)
        || (0x00C0..=0x024F).contains(&c)
        || (0x1E00..=0x1EFF).contains(&c)
        || (0x0370..=0x03FF).contains(&c)
        || (0x1F00..=0x1FFF).contains(&c)
        || (0x0400..=0x052F).contains(&c)
        || (0x2DE0..=0x2DFF).contains(&c)
        || (0x3040..=0x30FF).contains(&c)
        || (0x31F0..=0x31FF).contains(&c)
        || (0x3400..=0x4DBF).contains(&c)
        || (0x4E00..=0x9FFF).contains(&c)
        || (0xF900..=0xFAFF).contains(&c)
        || (0x20000..=0x2FA1F).contains(&c)
        // Common and Inherited: ASCII and Latin-1 punctuation, the combining
        // marks, general punctuation and the symbol blocks, the CJK symbols,
        // the variation selectors, the fullwidth forms, the musical and
        // mathematical alphanumerics, emoji, and the tag characters.
        || c < 0x0300
        || (0x0300..=0x036F).contains(&c)
        || (0x2000..=0x2BFF).contains(&c)
        || (0x3000..=0x303F).contains(&c)
        || (0xFE00..=0xFE0F).contains(&c)
        || (0xFE30..=0xFE4F).contains(&c)
        || (0xFF00..=0xFFEF).contains(&c)
        || (0x1D000..=0x1D7FF).contains(&c)
        || (0x1F000..=0x1FAFF).contains(&c)
        || (0xE0000..=0xE00FF).contains(&c)
}

/// Scripts HarfBuzz gives to a shaper of their own, so a default-shaper
/// implementation must not be gated on them: `arabic`, `hangul`, `hebrew`,
/// `thai`, `indic`, `khmer`, `myanmar` and the USE. None of them is built yet.
fn complex_script(ch: char) -> bool {
    let c = ch as u32;
    // Hebrew has a shaper of its own too (a composition step), so it is out
    // even though the default shaper would otherwise handle it.
    (0x0590..=0x05FF).contains(&c)
        // Arabic, Syriac, Thaana, Nko, Samaritan, Mandaic, and the presentation
        // forms.
        || (0x0600..=0x08FF).contains(&c)
        || (0xFB50..=0xFDFF).contains(&c)
        || (0xFE70..=0xFEFF).contains(&c)
        // Indic, Sinhala, Tibetan, Myanmar, Khmer, Thai, Lao — one span.
        || (0x0900..=0x109F).contains(&c)
        || (0x0E00..=0x0EFF).contains(&c)
        || (0x1780..=0x17FF).contains(&c)
        // Hangul jamo and syllables.
        || (0x1100..=0x11FF).contains(&c)
        || (0xA960..=0xA97F).contains(&c)
        || (0xAC00..=0xD7FF).contains(&c)
        // Mongolian, and the BMP blocks the USE covers.
        || (0x1800..=0x18AF).contains(&c)
        || (0x1700..=0x177F).contains(&c)
        || (0x1900..=0x1CFF).contains(&c)
        // The SMP blocks the USE covers.
        || (0x10A00..=0x10A5F).contains(&c)
        || (0x11000..=0x11FFF).contains(&c)
        || (0x1E900..=0x1E95F).contains(&c)
}

/// A `--features=…` spec, as the shaper can take it: **global over the run,
/// on or off**, because that is all a `ShapeRequest` carries. `None` means the spec asks for something
/// this shaper has no word for, and the case is skipped by name.
///
/// The forms the corpus uses: `"test"`, `-liga`, `ss01`, `calt=0`, and
/// comma-separated lists of those. What is refused: a value above one
/// (`salt=2`, `rand=2`) and a range (`tag[2:4]`), because `ShapeRequest` says
/// neither.
fn parse_features(option: &str) -> Option<Vec<Feature>> {
    let spec = option.strip_prefix("--features=")?.trim_matches('"');
    if spec.is_empty() {
        return None;
    }
    let mut out = Vec::new();
    for item in spec.split(',') {
        let item = item.trim();
        let (mut on, rest) = match item.strip_prefix('-') {
            Some(rest) => (false, rest),
            None => (true, item.strip_prefix('+').unwrap_or(item)),
        };
        let tag = match rest.split_once('=') {
            Some((tag, "0")) => {
                on = false;
                tag
            }
            Some((tag, "1")) => {
                on = true;
                tag
            }
            // A value above one, which is an alternate index and not a switch.
            Some(_) => return None,
            None => rest,
        };
        // A four-byte ASCII tag and nothing else: a range makes it longer.
        if tag.len() != 4 || !tag.bytes().all(|b| (0x20..0x7f).contains(&b)) {
            return None;
        }
        let mut bytes = [0u8; 4];
        bytes.copy_from_slice(tag.as_bytes());
        out.push(Feature { tag: bytes, on });
    }
    // The pool is per dispatch and a request names a slice of it; a case that
    // wanted more than the whole pool could never be batched.
    (out.len() <= MAX_SHAPE_FEATURES as usize).then_some(out)
}

/// Whether an option changes what a shaper *does*, as against what the test
/// harness prints.
///
/// The distinction earns most of the corpus: 3853 in-house cases and 394
/// text-rendering ones carry nothing but serialization flags, and skipping on
/// "options are set" would have thrown all of them away. What is left here is
/// the real exclusions, and every one of them is something the shaper does not
/// do yet: variations, a forced direction or script, cluster levels and face
/// indices.
///
/// `--features` is not on this list: a spec that is a plain list of tags on
/// or off is one `ShapeRequest` can carry, and that is all 276 of aots.
fn shaping_option(option: &str) -> bool {
    let name = option.split('=').next().unwrap_or(option);
    match name {
        // Taken where the spec is global and on-or-off; skipped by name where
        // it is a value or a range.
        "--features" => parse_features(option).is_none(),
        // Serialization only.
        "--no-glyph-names" | "--no-positions" | "--no-clusters" | "--no-advances"
        | "--show-flags" | "--show-extents" | "--ned" | "--verify" | "--single-par"
        | "--font-funcs" | "--utf8-clusters" => false,
        // `--shaper=ot` is what this is; anything else is not.
        "--shaper" => option != "--shaper=ot",
        // `--direction=ltr` is what this is.
        "--direction" => option != "--direction=ltr",
        // Handled by the caller, which keeps the case when the input has no
        // default-ignorable codepoint in it.
        "--remove-default-ignorables" => false,
        _ => true,
    }
}

/// Read every `.tests` file under the data root, keeping the cases the shaper
/// is gated on and tallying the skips with the reason.
fn read_cases(data: &Path) -> (Vec<Case>, BTreeMap<String, Tally>) {
    let mut cases = Vec::new();
    let mut tally: BTreeMap<String, Tally> = BTreeMap::new();
    let mut files = Vec::new();
    let mut stack = vec![data.to_path_buf()];
    while let Some(dir) = stack.pop() {
        let Ok(entries) = std::fs::read_dir(&dir) else {
            continue;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                stack.push(path);
            } else if path.extension().is_some_and(|e| e == "tests") {
                files.push(path);
            }
        }
    }
    files.sort();

    for file in files {
        let name = file
            .strip_prefix(data)
            .unwrap_or(&file)
            .to_string_lossy()
            .into_owned();
        let Ok(text) = std::fs::read_to_string(&file) else {
            continue;
        };
        for (line_no, line) in text.lines().enumerate() {
            let line = line.trim();
            // `#` is a comment and `@` a directive for the generator.
            if line.is_empty() || line.starts_with('#') || line.starts_with('@') {
                continue;
            }
            let mut fields = line.splitn(4, ';');
            let (Some(font), Some(options), Some(input), Some(expected)) =
                (fields.next(), fields.next(), fields.next(), fields.next())
            else {
                continue;
            };
            let entry = tally.entry(name.clone()).or_default();
            let Some(text) = decode_input(input) else {
                entry.unreadable += 1;
                continue;
            };
            if text.chars().any(complex_script) {
                entry.complex += 1;
                continue;
            }
            if !text.chars().all(classified) {
                entry.unclassified += 1;
                continue;
            }
            let mut skipped = false;
            for option in options.split_whitespace() {
                if shaping_option(option) {
                    *entry.options.entry(option_name(option)).or_default() += 1;
                    skipped = true;
                    break;
                }
            }
            if skipped {
                continue;
            }
            // `--remove-default-ignorables` deletes them rather than hiding
            // them, which changes the glyph count. A string with none in it is
            // the same either way.
            if options.contains("--remove-default-ignorables")
                && text.chars().any(|ch| default_ignorable(ch as u32))
            {
                *entry
                    .options
                    .entry("--remove-default-ignorables".to_owned())
                    .or_default() += 1;
                continue;
            }
            // Font paths are `../fonts/NAME`, relative to the `tests/` dir.
            let font_path = file.parent().map(|dir| dir.join(font)).unwrap_or_default();
            if !font_path.is_file() {
                entry.unreadable += 1;
                continue;
            }
            let features = options
                .split_whitespace()
                .find(|option| option.starts_with("--features="))
                .and_then(parse_features)
                .unwrap_or_default();
            entry.kept += 1;
            cases.push(Case {
                origin: format!("{name}:{}", line_no + 1),
                font: font_path,
                options: options.to_owned(),
                features,
                text,
                expected: expected.to_owned(),
            });
        }
    }
    (cases, tally)
}

fn option_name(option: &str) -> String {
    option.split('=').next().unwrap_or(option).to_owned()
}

/// Why the cases of one file were or were not taken.
#[derive(Default)]
struct Tally {
    kept: usize,
    complex: usize,
    /// A script the placeholder classifier does not name; the Unicode Script
    /// property would.
    unclassified: usize,
    unreadable: usize,
    /// Option name → how many cases it excluded.
    options: BTreeMap<String, usize>,
}

/// The Default_Ignorable_Code_Point ranges, the same list `shape.slang` walks.
fn default_ignorable(c: u32) -> bool {
    matches!(c,
        0x00AD | 0x034F | 0x061C
        | 0x17B4..=0x17B5 | 0x180B..=0x180F
        | 0x200B..=0x200F | 0x202A..=0x202E | 0x2060..=0x206F
        | 0xFE00..=0xFE0F | 0xFEFF | 0xFFF0..=0xFFF8
        | 0x1BCA0..=0x1BCA3 | 0x1D173..=0x1D17A
        | 0xE0000..=0xE0FFF)
}

/// A `.tests` input field: `U+0041,U+0042`, or bare hex codepoints.
fn decode_input(field: &str) -> Option<String> {
    let field = field.trim();
    if field.is_empty() {
        return Some(String::new());
    }
    let mut out = String::new();
    for part in field.split(',') {
        let part = part.trim();
        let hex = part.strip_prefix("U+").unwrap_or(part);
        let value = u32::from_str_radix(hex, 16).ok()?;
        out.push(char::from_u32(value)?);
    }
    Some(out)
}

/// One item of an expected string, when it names glyphs by id rather than by
/// name: `gid7=0@-12,3+520` or `17`.
struct Expected {
    gid: u32,
    x_offset: i32,
    y_offset: i32,
    x_advance: i32,
    /// Whether the line carried positions at all.
    positioned: bool,
}

/// Parse an expected string, or `None` when it names a glyph by a name this
/// harness would have to read the `post` table to resolve — which is the
/// serializer's job and not the shaper's.
fn parse_expected(text: &str, positions: bool) -> Option<Vec<Expected>> {
    let text = text.trim();
    if text.is_empty() {
        return Some(Vec::new());
    }
    if text == "*" {
        return None;
    }
    let inner = text.strip_prefix('[')?.strip_suffix(']')?;
    if inner.is_empty() {
        return Some(Vec::new());
    }
    let mut out = Vec::new();
    for item in inner.split('|') {
        // glyph [ "=" cluster ] [ "@" dx "," dy ] [ "+" adv [ "," yadv ] ]
        let head_end = item.find(['=', '@', '+', '#', '<']).unwrap_or(item.len());
        let (head, mut rest) = item.split_at(head_end);
        let gid: u32 = head.strip_prefix("gid").unwrap_or(head).parse().ok()?;
        let mut x_offset = 0i32;
        let mut y_offset = 0i32;
        let mut x_advance = 0i32;
        let mut positioned = false;
        if let Some(after) = rest.strip_prefix('=') {
            let end = after.find(['@', '+', '#', '<']).unwrap_or(after.len());
            rest = &after[end..];
        }
        if let Some(after) = rest.strip_prefix('@') {
            let end = after.find(['+', '#', '<']).unwrap_or(after.len());
            let (x, y) = after[..end].split_once(',')?;
            x_offset = x.parse().ok()?;
            y_offset = y.parse().ok()?;
            positioned = true;
            rest = &after[end..];
        }
        if let Some(after) = rest.strip_prefix('+') {
            let end = after.find(['#', '<']).unwrap_or(after.len());
            let field = &after[..end];
            let x = field.split(',').next().unwrap_or(field);
            x_advance = x.parse().ok()?;
            positioned = true;
        }
        out.push(Expected {
            gid,
            x_offset,
            y_offset,
            x_advance,
            positioned: positioned && positions,
        });
    }
    Some(out)
}

/// Which sfnt tables a font has, by tag — the harness reading the same
/// directory `Arena` reads, because what a case *needs* is often a table the
/// arena does not carry: `morx` and `kerx` are AAT, and a `kern` with no `GPOS` is
/// the legacy TrueType table HarfBuzz falls back to.
fn has_table(bytes: &[u8], tag: &[u8; 4]) -> bool {
    let Some(count) = bytes.get(4..6) else {
        return false;
    };
    let count = u16::from_be_bytes([count[0], count[1]]) as usize;
    (0..count).any(|i| bytes.get(12 + i * 16..16 + i * 16) == Some(&tag[..]))
}

/// The feature tags a layout table's FeatureList states, as four-byte arrays.
///
/// The harness reads them to name a case whose answer turns on a feature the
/// shaper does not enable — `rand`, which HarfBuzz turns on with a random value per
/// glyph and the shader does not enable.
fn feature_tags(table: &[u8]) -> Vec<[u8; 4]> {
    let be16 = |at: usize| -> usize {
        table
            .get(at..at + 2)
            .map(|b| u16::from_be_bytes([b[0], b[1]]) as usize)
            .unwrap_or(0)
    };
    let list = be16(6);
    let count = be16(list);
    (0..count)
        .filter_map(|i| {
            table
                .get(list + 2 + i * 6..list + 6 + i * 6)
                .map(|b| [b[0], b[1], b[2], b[3]])
        })
        .collect()
}

/// Why a case that did not agree is not a failure of the shaper. Every one is
/// something it does not do yet (docs/roadmap.md) or leaves out
/// by design — AAT, which no font on a Linux desktop ships, and HarfBuzz's
/// fallbacks for fonts without the OpenType tables — and every one is counted
/// and named.
#[derive(Default)]
struct Excused {
    /// The font's layout is AAT `morx`/`kerx`/`trak`, which the shaper does not read.
    aat: usize,
    /// The font kerns through the legacy TrueType `kern` table.
    legacy_kern: usize,
    /// The font has no GPOS, so HarfBuzz positions the marks itself.
    fallback_marks: usize,
    /// `frac`/`numr`/`dnom` around U+2044, whose mask needs Unicode general
    /// categories the shader does not have yet.
    fractions: usize,
    /// The `rand` feature.
    random: usize,
    /// harfrust's normaliser composed, decomposed or filled a space glyph.
    normaliser: usize,
    /// The run hit `MAX_RUN_GLYPHS` or `MAX_OPS` — a font built to expand.
    bounded: usize,
}

impl Excused {
    fn total(&self) -> usize {
        self.aat
            + self.legacy_kern
            + self.fallback_marks
            + self.fractions
            + self.random
            + self.normaliser
            + self.bounded
    }
}

fn harfbuzz_corpus(gpu: &Gpu) -> Result<usize> {
    let Some(root) = ensure_corpus() else {
        return Ok(0);
    };
    let data = corpus_data(&root);
    let (cases, tally) = read_cases(&data);
    let kept: usize = tally.values().map(|t| t.kept).sum();
    let complex: usize = tally.values().map(|t| t.complex).sum();
    let unclassified: usize = tally.values().map(|t| t.unclassified).sum();
    let unreadable: usize = tally.values().map(|t| t.unreadable).sum();
    let by_option = {
        let mut merged: BTreeMap<String, usize> = BTreeMap::new();
        for t in tally.values() {
            for (option, count) in &t.options {
                *merged.entry(option.clone()).or_default() += count;
            }
        }
        merged
    };
    println!();
    println!("=== HarfBuzz's corpus, at {} ===", data.display());
    println!(
        "  {kept} cases kept over {} files; {complex} skipped for a complex script (not shaped yet), \
         {unclassified} for a script that needs Unicode properties (not built), {unreadable} unreadable",
        tally.values().filter(|t| t.kept > 0).count(),
    );
    for (option, count) in &by_option {
        println!("  skipped for {option}: {count}");
    }
    println!("  by file (kept/complex/by-option):");
    for (file, t) in &tally {
        if t.kept > 0 {
            println!(
                "    {file}: {} kept, {} complex, {} unclassified, {} by option",
                t.kept,
                t.complex,
                t.unclassified,
                t.options.values().sum::<usize>()
            );
        }
    }
    for (file, t) in &tally {
        if t.kept == 0 {
            println!(
                "    {file}: none kept ({} complex, {} unclassified, {} by option, \
                 {} unreadable)",
                t.complex,
                t.unclassified,
                t.options.values().sum::<usize>(),
                t.unreadable
            );
        }
    }

    // Group by font so each one is sliced and uploaded once — and by the
    // features a case forces as well: the feature pool is a *dispatch's*
    // and a request names a slice of it, so two cases that force different
    // features are two dispatches. Every aots file forces the same one tag, so
    // this splits nothing that was together before.
    let mut by_font: BTreeMap<(PathBuf, String), Vec<&Case>> = BTreeMap::new();
    for case in &cases {
        let key = case
            .features
            .iter()
            .map(|f| {
                format!(
                    "{}{}",
                    if f.on { '+' } else { '-' },
                    String::from_utf8_lossy(&f.tag)
                )
            })
            .collect::<Vec<_>>()
            .join(",");
        by_font
            .entry((case.font.clone(), key))
            .or_default()
            .push(case);
    }

    let mut failures = 0usize;
    let mut excused = Excused::default();
    let mut compared = 0usize;
    let mut bad_font = 0usize;
    let mut oracle_checked = 0usize;
    let mut oracle_drift = 0usize;
    let mut printed = 0usize;
    let mut deepest = 0u32;
    for ((font, _features), cases) in &by_font {
        let Ok(bytes) = std::fs::read(font) else {
            bad_font += cases.len();
            continue;
        };
        let Ok(arena) = Arena::of(&bytes, 0) else {
            bad_font += cases.len();
            continue;
        };
        let Ok(oracle) = Oracle::new(&bytes) else {
            bad_font += cases.len();
            continue;
        };
        let upem = arena.faces()[0].upem as f32;
        let aat = has_table(&bytes, b"morx")
            || has_table(&bytes, b"mort")
            || has_table(&bytes, b"kerx")
            || has_table(&bytes, b"trak");
        let table = |slot: usize| -> &[u8] {
            let (off, len) = arena.faces()[0].tables[slot];
            &arena.bytes()[off as usize..off as usize + len as usize]
        };
        let gpos_features = feature_tags(table(4));
        let has_gpos = !gpos_features.is_empty();
        // The legacy TrueType `kern` table is what HarfBuzz falls back to when
        // GPOS states no `kern` feature — and a font with an *empty* GPOS is
        // exactly that case.
        let legacy_kern = has_table(&bytes, b"kern") && !gpos_features.contains(b"kern");
        let random = feature_tags(table(3)).contains(b"rand");

        let mut batch = Batch::new();
        for case in cases {
            batch
                .push_with_features(&case.text, upem, &case.features)
                .expect("a group shares one feature set, which fits the pool");
        }
        let timing = gpu.run(&arena, &batch)?;

        for (index, case) in cases.iter().enumerate() {
            let run = timing.runs[index];
            let request = batch.requests()[index];
            let ours = &timing.glyphs
                [request.out_start as usize..request.out_start as usize + run.glyph_count as usize];
            let theirs = oracle.shape_with(&case.text, &case.features);
            compared += 1;
            deepest = deepest.max(run.depth);

            // The oracle against the file's own expectation, where the file
            // names glyphs by id: a drift here means the corpus has moved past
            // harfrust 0.12.0, and is reported rather than counted as a
            // failure of the shaper.
            // `--ned` is hb-shape's "no extra data": it prints no advances, and
            // the `@x,y` it does print is the glyph's **position** rather than
            // its offset. Every aots file sets it, and reading those numbers as
            // offsets makes 129 cases look like oracle drift. The ids are still compared, which is what this check is for.
            let positions =
                !case.options.contains("--no-positions") && !case.options.contains("--ned");
            if let Some(expected) = parse_expected(&case.expected, positions) {
                oracle_checked += 1;
                let mut drift = expected.len() != theirs.len();
                if !drift {
                    for (want, got) in expected.iter().zip(theirs.iter()) {
                        if want.gid != got.gid
                            || (want.positioned
                                && (want.x_offset != got.x_offset
                                    || want.y_offset != got.y_offset
                                    || want.x_advance != got.x_advance))
                        {
                            drift = true;
                            break;
                        }
                    }
                }
                if drift {
                    oracle_drift += 1;
                    if oracle_drift <= 8 {
                        println!(
                            "  oracle drift {} [{}] {}\n      harfrust {}\n      file     {}",
                            case.origin,
                            case.options,
                            codepoints(&case.text),
                            render_theirs(&theirs),
                            case.expected.trim(),
                        );
                    }
                }
            }

            let mut bad = theirs.len() != ours.len();
            // A glyph that is `.notdef` here and real there is the normaliser
            // or the space fallback filling in a codepoint the face lacks.
            let mut only_notdef = theirs.len() == ours.len();
            let mut pen = 0i32;
            if !bad {
                for (mine, yours) in ours.iter().zip(theirs.iter()) {
                    let want_x = i64::from(pen + yours.x_offset) * 64;
                    let want_y = i64::from(yours.y_offset) * 64;
                    pen += yours.x_advance;
                    // Clusters are compared with the same tolerance as the
                    // rest: `merge_clusters` is the shaper's, not the
                    // serializer's, and a bidi pass would reorder by what it
                    // produces.
                    if mine.gid != yours.gid
                        || i64::from(mine.x) != want_x
                        || i64::from(mine.y) != want_y
                        || mine.cluster != yours.cluster
                    {
                        bad = true;
                        if !(mine.gid == 0 && yours.gid != 0) {
                            only_notdef = false;
                        }
                    }
                }
            }
            if bad {
                if aat {
                    excused.aat += 1;
                    continue;
                }
                if legacy_kern {
                    excused.legacy_kern += 1;
                    continue;
                }
                if random {
                    excused.random += 1;
                    continue;
                }
                if case.text.contains('\u{2044}') {
                    excused.fractions += 1;
                    continue;
                }
                if run.flags & (SHAPE_RUN_TRUNCATED | SHAPE_RUN_OUT_OF_OPS) != 0 {
                    excused.bounded += 1;
                    continue;
                }
                // A font with no GPOS gets HarfBuzz's own fallback mark
                // positioning, which shifts a mark back over the base it
                // follows. The shader has none (`slang/modules/shape.slang` says so in its header);
                // the ids and clusters still have to agree exactly, and the
                // mark is GDEF's rather than Unicode's — which is what the
                // aots cases need, their "marks" being control codepoints.
                let marked = ours.iter().any(|g| g.flags & SHAPE_GLYPH_MARK != 0);
                let ids_agree = theirs.len() == ours.len()
                    && ours
                        .iter()
                        .zip(theirs.iter())
                        .all(|(m, y)| m.gid == y.gid && m.cluster == y.cluster);
                if !has_gpos && ids_agree && (marked || case.text.chars().any(combining)) {
                    excused.fallback_marks += 1;
                    continue;
                }
                if only_notdef || (theirs.len() != ours.len() && case.text.chars().any(combining)) {
                    excused.normaliser += 1;
                    continue;
                }
                failures += 1;
                if printed < 40 {
                    printed += 1;
                    println!(
                        "  {} [{}] {} flags {:#x}\n      ours     {}\n      harfrust {}\n      \
                         file     {}",
                        case.origin,
                        case.options,
                        codepoints(&case.text),
                        run.flags,
                        render_ours(ours),
                        render_theirs(&theirs),
                        case.expected.trim(),
                    );
                }
            }
        }
    }

    println!(
        "  {compared} compared, {failures} mismatched, {} excused, {bad_font} whose font would \
         not open; deepest nesting {deepest}",
        excused.total()
    );
    println!(
        "  excused: {} AAT layout, {} the legacy kern table, {} HarfBuzz's fallback mark \
         positioning, {} automatic fractions, {} the rand feature, {} the normaliser or the \
         space fallback, {} bounded by MAX_RUN_GLYPHS or MAX_OPS",
        excused.aat,
        excused.legacy_kern,
        excused.fallback_marks,
        excused.fractions,
        excused.random,
        excused.normaliser,
        excused.bounded,
    );
    println!(
        "  the oracle against the files' own expectations: {oracle_checked} checked, \
         {oracle_drift} drifted"
    );
    Ok(failures)
}

fn codepoints(text: &str) -> String {
    text.chars()
        .map(|ch| format!("U+{:04X}", ch as u32))
        .collect::<Vec<_>>()
        .join(",")
}

/// The shader's run in the corpus's own shape: id, pen, advance — the pen is
/// 26.6 at a size of one em, so a division by 64 is the font unit.
fn render_ours(glyphs: &[ShapedGlyph]) -> String {
    let mut out = Vec::new();
    for (i, glyph) in glyphs.iter().enumerate() {
        let x = i64::from(glyph.x) / 64;
        let advance = if i + 1 < glyphs.len() {
            i64::from(glyphs[i + 1].x) / 64 - x
        } else {
            0
        };
        out.push(format!(
            "gid{}={}@{},{}+{}",
            glyph.gid,
            glyph.cluster,
            x,
            i64::from(glyph.y) / 64,
            advance
        ));
    }
    out.join("|")
}

fn render_theirs(glyphs: &[RefGlyph]) -> String {
    glyphs
        .iter()
        .map(|g| {
            format!(
                "gid{}={}@{},{}+{}",
                g.gid, g.cluster, g.x_offset, g.y_offset, g.x_advance
            )
        })
        .collect::<Vec<_>>()
        .join("|")
}


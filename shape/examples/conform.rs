/// The strings a desktop user interface shapes, plus the ones that break
/// shapers.
// Grouped by where the strings come from, which rustfmt would spread over a
// hundred lines of one each.
#[rustfmt::skip]
fn ui_strings() -> Vec<String> {
    let mut out: Vec<String> = Vec::new();

    // Clock strings in two formats, a session menu's rows, a window menu's
    // labels, and settings rows that carry words rather than numbers.
    for s in [
        "22:15", "22:51", "09:04", "00:00", "11:11", "1:23 pm", "12:00 am", "Mon 12 Sep",
        // A session menu.
        "Lock", "Log Out", "Suspend", "Restart", "Shut Down",
        // A window menu.
        "New window", "Close", "Pin to dock", "Unpin from dock",
        // Settings rows.
        "Wi-Fi", "Bluetooth", "Caffeine", "Volume", "Muted", "Disconnected",
        "Bluetooth — off", "Not connected", "Connecting…",
        // Numbers a status display draws.
        "100%", "42%", "3%", "0.0 W", "12.4 W", "1.2 GHz", "37°C", "8/16",
    ] {
        out.push(s.to_string());
    }

    // The hand list: the ligatures, the classic kerning pairs, the punctuation
    // a UI shows and the digits.
    for s in [
        "fi", "fl", "ff", "ffi", "ffl", "final", "fluff", "affix", "office",
        "AV", "To", "Ta", "Tо", "LT", "Yo", "Av", "P.", "r.", "y,",
        "AVATAR", "Today", "Waffle", "VAV",
        "0123456789", "—", "…", "– — …", "“quoted”", "it's", "a–b—c…d",
        // Latin-1 and a few Greek/Cyrillic letters, all of which Noto has and
        // all of which kern differently from ASCII.
        "Ärger", "naïve", "Ångström", "café", "ÆØÅ", "Ελλάς", "Привет",
        // A space-heavy string (the space glyph kerns against nothing but is in
        // every coverage table), and an empty one.
        "  a  b  ", "",
        // The joiners, whose skipping the iterator's rules turn on: a ZWNJ
        // between f and i must *stop* the ligature, a ZWJ must not.
        "f\u{200C}i", "f\u{200D}i", "a\u{200B}b", "soft\u{00AD}hyphen",
        // Combining marks, which are GPOS mark attachment and GDEF classes.
        "a\u{0301}", "e\u{0300}u\u{0302}", "n\u{0303}o",
    ] {
        out.push(s.to_string());
    }

    out
}

fn ui_corpus(gpu: &Gpu) -> Result<usize> {
    let mut fonts: Vec<PathBuf> = [ADWAITA_SANS, NOTO_SANS, NOTO_MONO]
        .iter()
        .map(PathBuf::from)
        .filter(|path| path.exists())
        .collect();
    if fonts.is_empty() {
        fonts.extend(fc_sans());
    }
    if fonts.is_empty() {
        bail!(
            "no font to check: none of {ADWAITA_SANS}, {NOTO_SANS}, {NOTO_MONO} is installed \
             and fontconfig names no sans-serif"
        );
    }
    let corpus = ui_strings();
    println!("the UI corpus: {} strings", corpus.len());

    let mut failures = 0usize;
    for font in &fonts {
        println!();
        println!("=== {} ===", font.display());
        let data = std::fs::read(font).with_context(|| font.display().to_string())?;

        let started = Instant::now();
        let arena = Arena::of(&data, 0).map_err(|err| anyhow::anyhow!("{err}"))?;
        let sliced = started.elapsed();
        let info = arena.faces()[0];
        println!(
            "sliced in {:.2} ms: {} glyphs at {} upem, {} — {} KiB of arena",
            sliced.as_secs_f64() * 1e3,
            info.glyph_count,
            info.upem,
            info.table_sizes(),
            arena.bytes().len().div_ceil(1024),
        );

        let oracle = Oracle::new(&data)?;
        for size in SIZES {
            failures += check_at(gpu, &arena, &oracle, &corpus, size, info.upem as f32)?;
        }
    }
    Ok(failures)
}

/// The system's sans-serif, through fontconfig, for a machine with none of
/// the three named fonts installed.
fn fc_sans() -> Option<PathBuf> {
    let output = std::process::Command::new("fc-match")
        .args(["--format=%{file}", "sans-serif"])
        .output()
        .ok()?;
    let path = PathBuf::from(String::from_utf8(output.stdout).ok()?.trim());
    path.is_file().then_some(path)
}

/// Whether a codepoint is a combining mark — the rough shape of
/// Canonical_Combining_Class ≠ 0, which belongs to the Unicode normaliser the
/// shader does not have yet (docs/roadmap.md, *Unicode*) and is here only
/// to name the cases harfrust's normaliser composes and the shader does not.
fn combining(ch: char) -> bool {
    let c = ch as u32;
    (0x0300..=0x036F).contains(&c)
        || (0x1AB0..=0x1AFF).contains(&c)
        || (0x1DC0..=0x1DFF).contains(&c)
        || (0x20D0..=0x20F0).contains(&c)
        || (0xFE20..=0xFE2F).contains(&c)
}

/// One (font, size): shape the whole corpus in one batch and compare.
fn check_at(
    gpu: &Gpu,
    arena: &Arena,
    oracle: &Oracle,
    corpus: &[String],
    px_size: f32,
    upem: f32,
) -> Result<usize> {
    let mut batch = Batch::new();
    for text in corpus {
        batch.push(text, px_size);
    }
    let timing = gpu.run(arena, &batch)?;

    // The reference's font units, converted to 26.6 **the way the shader
    // converts them** — same operations, same order, same precision.
    //
    // Doing this in `f64` looks harmless until a fifty-two-character
    // window title lands one glyph on a rounding boundary: the shader's
    // `float(pen) * scale` and an `f64` `(pen as f64) * scale` differ by one
    // 26.6 unit there, on every adapter it was run on. That is not two shapers
    // disagreeing — the shaping is integers and it agrees exactly — it is two
    // *conversions* disagreeing, and the conversion is this harness's own arithmetic
    // rather than harfrust's. So the harness does the shader's arithmetic: the
    // tolerance stays zero and what it is zero about is the shaping.
    let scale = px_size / upem * 64.0;
    // `roundAway` in `shape.slang`, written out.
    let round_away = |value: f32| -> i64 {
        if value >= 0.0 {
            (value + 0.5).floor() as i64
        } else {
            -((-value + 0.5).floor() as i64)
        }
    };
    let mut failures = 0usize;
    let mut printed = 0usize;
    let mut normalised = 0usize;
    let mut worst = 0i64;
    let mut worst_where = String::new();

    for (index, text) in corpus.iter().enumerate() {
        let run = timing.runs[index];
        let request = batch.requests()[index];
        let ours = &timing.glyphs
            [request.out_start as usize..request.out_start as usize + run.glyph_count as usize];
        if run.flags & (SHAPE_RUN_TRUNCATED | SHAPE_RUN_BAD_UTF8 | SHAPE_RUN_OUT_OF_OPS) != 0 {
            failures += 1;
            println!("    {text:?}: the run came back flagged {:#x}", run.flags);
            continue;
        }
        let theirs = oracle.shape(text);

        if theirs.len() != ours.len() {
            // harfrust normalises before GSUB (mode COMPOSED_DIACRITICS), so a
            // base and a combining mark the face has a precomposed glyph for
            // become one glyph there and stay two here. The shader has no
            // normaliser yet, so this is counted and named rather than failed
            // — but only when it is exactly that: a string with a combining
            // mark in it that the reference made *shorter*. Equal counts are
            // compared as usual, which is what tests mark attachment.
            if theirs.len() < ours.len() && text.chars().any(combining) {
                normalised += 1;
                continue;
            }
            failures += 1;
            if printed < 25 {
                printed += 1;
                println!(
                    "    {text:?}: {} glyphs here, {} in harfrust",
                    ours.len(),
                    theirs.len(),
                );
            }
            continue;
        }

        let mut bad = false;
        let mut pen = 0i32;
        for (position, (mine, yours)) in ours.iter().zip(theirs.iter()).enumerate() {
            // harfrust's pen: the running sum of the advances, plus this
            // glyph's own offset. The shader's is the same arithmetic done
            // before the one rounding.
            let want_x = round_away((pen + yours.x_offset) as f32 * scale);
            let want_y = round_away(yours.y_offset as f32 * scale);
            pen += yours.x_advance;
            let dx = i64::from(mine.x) - want_x;
            let dy = i64::from(mine.y) - want_y;
            if dx.abs() > worst {
                worst = dx.abs();
                worst_where = format!("{text:?} glyph {position}");
            }
            if mine.gid != yours.gid || dx != 0 || dy != 0 || mine.cluster != yours.cluster {
                bad = true;
                if printed < 25 {
                    printed += 1;
                    println!(
                        "    {text:?} glyph {position}: gid {} vs {}, x {} vs {want_x}, \
                         y {} vs {want_y} (26.6), cluster {} vs {}",
                        mine.gid, yours.gid, mine.x, mine.y, mine.cluster, yours.cluster,
                    );
                }
            }
        }
        if bad {
            failures += 1;
        }
    }

    let unsupported = timing
        .runs
        .iter()
        .filter(|run| run.flags & SHAPE_RUN_UNSUPPORTED != 0)
        .count();
    let depth = timing.runs.iter().map(|run| run.depth).max().unwrap_or(0);
    println!(
        "  {px_size:>4} px: {} compared, {failures} mismatched, {normalised} left to \
         normalisation (not built), {unsupported} unsupported; deepest nesting {depth}; \
         worst Δ {worst}/64 px{}",
        corpus.len(),
        if worst > 0 {
            format!(" at {worst_where}")
        } else {
            String::new()
        }
    );
    println!(
        "           upload {:.2} ms, one submit {:.2} ms, kernel {:.3} ms for {} strings \
         ({:.1} µs a string)",
        timing.upload_ms,
        timing.dispatch_ms,
        timing.pass_ms,
        corpus.len(),
        timing.pass_ms * 1e3 / corpus.len() as f64,
    );
    Ok(failures)
}


/// What one batch produced, and what it cost.
struct Timing {
    glyphs: Vec<ShapedGlyph>,
    runs: Vec<ShapeRun>,
    upload_ms: f64,
    /// One submit with the stage dispatches in it, wall clock to the fence. Dominated by
    /// the submit itself at this size, which is why `pass_ms` exists.
    dispatch_ms: f64,
    /// [`REPEATS`] runs of the stages in one submit, divided by [`REPEATS`]: the
    /// marginal cost of shaping the batch once, with the submit latency spread
    /// thin. This is the number to quote as "kernel time".
    pass_ms: f64,
}

/// Dispatches per timing submit. The pass is idempotent — same inputs, same
/// outputs, written to the same slots — so repeating it measures the kernel and
/// nothing else.
///
/// The count is chosen from the first dispatch rather than fixed, because a
/// fixed twenty once drove an integrated Radeon into a hard recovery:
/// twenty passes over a corpus in one submit is one command stream the driver
/// waits on, and it has a timeout.
const TIMING_BUDGET_MS: f64 = 200.0;
const MAX_REPEATS: u32 = 20;

struct Gpu {
    device: wgpu::Device,
    queue: wgpu::Queue,
    layout: wgpu::BindGroupLayout,
    /// One pipeline per shaping stage, in dispatch order.
    stages: Vec<wgpu::ComputePipeline>,
}

impl Gpu {
    fn new() -> Result<Gpu> {
        let instance = wgpu::Instance::new(wgpu::InstanceDescriptor {
            backends: wgpu::Backends::VULKAN,
            ..wgpu::InstanceDescriptor::new_without_display_handle()
        });

        // The integrated adapter, by device type, and never a name that says
        // NVIDIA.
        let adapters = pollster::block_on(instance.enumerate_adapters(wgpu::Backends::VULKAN));
        if adapters.is_empty() {
            bail!("no Vulkan adapter at all; is an ICD installed?");
        }
        for adapter in &adapters {
            let info = adapter.get_info();
            println!(
                "adapter seen: {} ({:?}, {})",
                info.name, info.device_type, info.driver_info
            );
        }
        // A CPU adapter is taken too, and for the same reason the discrete one
        // is refused: a software rasteriser cannot be the dGPU. That is what
        // lets this harness run on a machine whose only ICD is lavapipe.
        let adapter = adapters
            .iter()
            .find(|adapter| {
                let info = adapter.get_info();
                let usable = info.device_type == wgpu::DeviceType::IntegratedGpu
                    || info.device_type == wgpu::DeviceType::Cpu;
                usable && !info.name.to_ascii_uppercase().contains("NVIDIA")
            })
            .context(
                "no integrated or CPU Vulkan adapter; refusing to shape text on a discrete GPU. \
                 Set VK_DRIVER_FILES to the integrated GPU's driver \
                 (/usr/share/vulkan/icd.d/radeon_icd.x86_64.json, or intel_icd)",
            )?;
        let info = adapter.get_info();
        println!(
            "adapter chosen: {} ({:?}, {})",
            info.name, info.device_type, info.driver_info
        );

        if !adapter
            .features()
            .contains(wgpu::Features::PASSTHROUGH_SHADERS)
        {
            bail!(
                "adapter '{}' lacks PASSTHROUGH_SHADERS; the Slang->SPIR-V shader cannot be \
                 loaded here",
                info.name
            );
        }

        // Six storage buffers, the OpenType tables among them as one arena and
        // the stages' scratch.
        const STORAGE_BUFFERS: u32 = 6;
        let mut limits = wgpu::Limits::default();
        let ceiling = adapter.limits().max_storage_buffers_per_shader_stage;
        if ceiling < STORAGE_BUFFERS {
            bail!(
                "this adapter allows only {ceiling} storage buffers per compute stage; the \
                 shaping pass binds {STORAGE_BUFFERS}"
            );
        }
        limits.max_storage_buffers_per_shader_stage = STORAGE_BUFFERS.max(8).min(ceiling);

        // The shared device path (`punchcutter_core::gpu::open_device`): wgpu will not ask for
        // `VK_KHR_shader_clock`, and the shaper's SPIR-V carries the
        // capability, so without it the module cannot be loaded at all.
        let (device, queue, clock) = punchcutter_core::gpu::open_device(
            adapter,
            &wgpu::DeviceDescriptor {
                label: Some("punchcutter-shape-device"),
                required_features: wgpu::Features::PASSTHROUGH_SHADERS,
                required_limits: limits,
                ..Default::default()
            },
        )
        .context("Vulkan device creation failed")?;
        println!("shader clock: {clock:?}");

        // $PUNCHCUTTER_SLANG_DIR first, the source checkout second: the
        // harness can run on a test machine that has the modules but no
        // checkout.
        let source = std::env::var_os("PUNCHCUTTER_SLANG_DIR")
            .map(PathBuf::from)
            .filter(|dir| dir.is_dir())
            .unwrap_or_else(|| Path::new(env!("CARGO_MANIFEST_DIR")).join("../slang/modules"))
            .join("shape_demo.slang");
        let started = Instant::now();
        let program = punchcutter_slang::compile_program(
            &source,
            &punchcutter_shape::STAGE_ENTRIES,
            &Options::default(),
        )
        .map_err(|err| anyhow::anyhow!("{err}"))?;
        println!(
            "shader: {} KiB of SPIR-V in {} stages in {:.0} ms",
            program
                .entries
                .iter()
                .map(|entry| entry.spirv.len())
                .sum::<usize>()
                .div_ceil(1024),
            program.entries.len(),
            started.elapsed().as_secs_f64() * 1e3
        );

        let layout = create_layout(&device);
        let pipeline_layout = device.create_pipeline_layout(&wgpu::PipelineLayoutDescriptor {
            label: Some("punchcutter-shape-pl"),
            bind_group_layouts: &[Some(&layout)],
            immediate_size: 0,
        });

        // The passthrough path does no validation of its own, so the module
        // goes up inside an error scope rather than through the device's
        // uncaptured-error handler, which panics.
        let scope = device.push_error_scope(wgpu::ErrorFilter::Validation);
        let mut stages = Vec::new();
        for (entry, name) in program.entries.iter().zip(punchcutter_shape::STAGE_ENTRIES) {
            let started = Instant::now();
            stages.push(punchcutter_core::gpu::passthrough_pipeline(
                &device,
                &pipeline_layout,
                name,
                name,
                &entry.spirv,
                (punchcutter_shape::SHAPE_WORKGROUP, 1, 1),
            ));
            println!(
                "pipeline {name}: {} KiB, created in {:.0} ms",
                entry.spirv.len().div_ceil(1024),
                started.elapsed().as_secs_f64() * 1e3
            );
        }
        if let Some(err) = pollster::block_on(scope.pop()) {
            bail!("wgpu rejected the shaping module: {err}");
        }

        Ok(Gpu {
            device,
            queue,
            layout,
            stages,
        })
    }

    /// Upload the arena and the batch, dispatch, read both outputs back.
    fn run(&self, arena: &Arena, batch: &Batch) -> Result<Timing> {
        let params: ShapeParams = batch.params(arena);
        let words = batch.utf8_words();

        let started = Instant::now();
        let params_buffer = self.device.create_buffer(&wgpu::BufferDescriptor {
            label: Some("shape-params"),
            size: size_of::<ShapeParams>() as u64,
            usage: wgpu::BufferUsages::UNIFORM | wgpu::BufferUsages::COPY_DST,
            mapped_at_creation: false,
        });
        self.queue
            .write_buffer(&params_buffer, 0, bytes_of(&params));

        let requests = self.storage("shape-requests", bytes_of_slice(batch.requests()));
        let ot = self.storage("shape-ot", arena.bytes());
        let utf8 = self.storage("shape-utf8", words_bytes(&words));

        let glyph_bytes = u64::from(batch.glyph_capacity()) * size_of::<ShapedGlyph>() as u64;
        let run_bytes = (batch.len().max(1) * size_of::<ShapeRun>()) as u64;
        let out_glyphs = self.device.create_buffer(&wgpu::BufferDescriptor {
            label: Some("shape-out-glyphs"),
            size: glyph_bytes,
            usage: wgpu::BufferUsages::STORAGE | wgpu::BufferUsages::COPY_SRC,
            mapped_at_creation: false,
        });
        let out_runs = self.device.create_buffer(&wgpu::BufferDescriptor {
            label: Some("shape-out-runs"),
            size: run_bytes,
            usage: wgpu::BufferUsages::STORAGE | wgpu::BufferUsages::COPY_SRC,
            mapped_at_creation: false,
        });
        let scratch = self.device.create_buffer(&wgpu::BufferDescriptor {
            label: Some("shape-scratch"),
            size: punchcutter_shape::scratch_bytes(batch.len() as u32),
            usage: wgpu::BufferUsages::STORAGE,
            mapped_at_creation: false,
        });
        let glyph_readback = self.readback("shape-glyph-readback", glyph_bytes);
        let run_readback = self.readback("shape-run-readback", run_bytes);

        let bind_group = self.device.create_bind_group(&wgpu::BindGroupDescriptor {
            label: Some("shape-bg"),
            layout: &self.layout,
            entries: &[
                entry(0, &params_buffer),
                entry(1, &requests),
                entry(2, &ot),
                entry(3, &utf8),
                entry(4, &out_glyphs),
                entry(5, &out_runs),
                entry(6, &scratch),
            ],
        });
        self.queue.submit([]);
        self.device
            .poll(wgpu::PollType::wait_indefinitely())
            .map_err(|err| anyhow::anyhow!("the upload never completed: {err}"))?;
        let upload_ms = started.elapsed().as_secs_f64() * 1e3;

        let started = Instant::now();
        let mut encoder = self
            .device
            .create_command_encoder(&wgpu::CommandEncoderDescriptor {
                label: Some("shape-encoder"),
            });
        {
            let mut pass = encoder.begin_compute_pass(&wgpu::ComputePassDescriptor {
                label: Some("shape-pass"),
                timestamp_writes: None,
            });
            pass.set_bind_group(0, &bind_group, &[]);
            for stage in &self.stages {
                pass.set_pipeline(stage);
                pass.dispatch_workgroups(batch.workgroups(), 1, 1);
            }
        }
        encoder.copy_buffer_to_buffer(&out_glyphs, 0, &glyph_readback, 0, glyph_bytes);
        encoder.copy_buffer_to_buffer(&out_runs, 0, &run_readback, 0, run_bytes);
        self.queue.submit([encoder.finish()]);
        self.device
            .poll(wgpu::PollType::wait_indefinitely())
            .map_err(|err| anyhow::anyhow!("the dispatch never completed: {err}"))?;
        let dispatch_ms = started.elapsed().as_secs_f64() * 1e3;

        // The same pass REPEATS times in one submit, to separate the kernel from
        // the submit. Nothing is copied out of it; the readback above already
        // holds the answer, and the pass writes the same bytes every time.
        let repeats = ((TIMING_BUDGET_MS / dispatch_ms.max(0.01)) as u32).clamp(1, MAX_REPEATS);
        let started = Instant::now();
        let mut encoder = self
            .device
            .create_command_encoder(&wgpu::CommandEncoderDescriptor {
                label: Some("shape-timing-encoder"),
            });
        {
            let mut pass = encoder.begin_compute_pass(&wgpu::ComputePassDescriptor {
                label: Some("shape-timing-pass"),
                timestamp_writes: None,
            });
            pass.set_bind_group(0, &bind_group, &[]);
            for _ in 0..repeats {
                for stage in &self.stages {
                    pass.set_pipeline(stage);
                    pass.dispatch_workgroups(batch.workgroups(), 1, 1);
                }
            }
        }
        self.queue.submit([encoder.finish()]);
        self.device
            .poll(wgpu::PollType::wait_indefinitely())
            .map_err(|err| anyhow::anyhow!("the timing dispatch never completed: {err}"))?;
        let pass_ms = started.elapsed().as_secs_f64() * 1e3 / f64::from(repeats);

        let glyphs = self.read::<ShapedGlyph>(&glyph_readback)?;
        let runs = self.read::<ShapeRun>(&run_readback)?;
        Ok(Timing {
            glyphs,
            runs,
            upload_ms,
            dispatch_ms,
            pass_ms,
        })
    }

    fn storage(&self, label: &str, bytes: &[u8]) -> wgpu::Buffer {
        // A zero-sized buffer is not a thing; an empty run gets one dead
        // element, which the counts keep the shader out of.
        let size = (bytes.len() as u64).max(16);
        let buffer = self.device.create_buffer(&wgpu::BufferDescriptor {
            label: Some(label),
            size,
            usage: wgpu::BufferUsages::STORAGE | wgpu::BufferUsages::COPY_DST,
            mapped_at_creation: false,
        });
        if !bytes.is_empty() {
            self.queue.write_buffer(&buffer, 0, bytes);
        }
        buffer
    }

    fn readback(&self, label: &str, size: u64) -> wgpu::Buffer {
        self.device.create_buffer(&wgpu::BufferDescriptor {
            label: Some(label),
            size,
            usage: wgpu::BufferUsages::MAP_READ | wgpu::BufferUsages::COPY_DST,
            mapped_at_creation: false,
        })
    }

    fn read<T: punchcutter_core::plain::Plain + Default>(
        &self,
        buffer: &wgpu::Buffer,
    ) -> Result<Vec<T>> {
        let (tx, rx) = std::sync::mpsc::sync_channel(1);
        buffer.slice(..).map_async(wgpu::MapMode::Read, move |r| {
            let _ = tx.send(r);
        });
        self.device
            .poll(wgpu::PollType::wait_indefinitely())
            .map_err(|err| anyhow::anyhow!("the readback poll failed: {err}"))?;
        rx.recv()
            .context("the map callback never fired")?
            .context("the readback buffer could not be mapped")?;
        let out = {
            let view = buffer
                .slice(..)
                .get_mapped_range()
                .map_err(|err| anyhow::anyhow!("the mapped range is unavailable: {err}"))?;
            let mut out = Vec::with_capacity(view.len() / size_of::<T>());
            for chunk in view.chunks_exact(size_of::<T>()) {
                let mut value = T::default();
                assert!(
                    punchcutter_core::plain::write_from_bytes(&mut value, chunk),
                    "a chunk of exactly size_of::<T>() bytes"
                );
                out.push(value);
            }
            out
        };
        buffer.unmap();
        Ok(out)
    }
}

fn words_bytes<T: Copy>(words: &[T]) -> &[u8] {
    // SAFETY: `u32` has no padding and no invalid bit patterns, and `u8` has
    // alignment 1; the lifetime is the borrow's.
    unsafe { std::slice::from_raw_parts(words.as_ptr().cast::<u8>(), size_of_val(words)) }
}

fn entry(binding: u32, buffer: &wgpu::Buffer) -> wgpu::BindGroupEntry<'_> {
    wgpu::BindGroupEntry {
        binding,
        resource: buffer.as_entire_binding(),
    }
}

fn create_layout(device: &wgpu::Device) -> wgpu::BindGroupLayout {
    let storage = |binding: u32, read_only: bool| wgpu::BindGroupLayoutEntry {
        binding,
        visibility: wgpu::ShaderStages::COMPUTE,
        ty: wgpu::BindingType::Buffer {
            ty: wgpu::BufferBindingType::Storage { read_only },
            has_dynamic_offset: false,
            min_binding_size: None,
        },
        count: None,
    };
    device.create_bind_group_layout(&wgpu::BindGroupLayoutDescriptor {
        label: Some("punchcutter-shape-bgl"),
        entries: &[
            wgpu::BindGroupLayoutEntry {
                binding: 0,
                visibility: wgpu::ShaderStages::COMPUTE,
                ty: wgpu::BindingType::Buffer {
                    ty: wgpu::BufferBindingType::Uniform,
                    has_dynamic_offset: false,
                    min_binding_size: None,
                },
                count: None,
            },
            storage(1, true),
            storage(2, true),
            // The strings buffer: read-write because `ShapeTables.utf8` is an
            // `RWStructuredBuffer` (a host may compose strings into the same
            // buffer, and Slang will not pass one as a `StructuredBuffer`).
            // This harness never writes it; the descriptor has to match the
            // declaration.
            storage(3, false),
            storage(4, false),
            storage(5, false),
            // The stages' working state, one `ShapeScratch` per request.
            storage(6, false),
        ],
    })
}

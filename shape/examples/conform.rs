/// What `fc-match sans-serif` answers on a stock Fedora desktop. The three are
/// checked where they are installed, and the system's sans-serif when none is.
const ADWAITA_SANS: &str = "/usr/share/fonts/adwaita-sans-fonts/AdwaitaSans-Regular.ttf";
/// The variable Noto Sans, read at its default instance.
const NOTO_SANS: &str = "/usr/share/fonts/google-noto-vf/NotoSans[wght].ttf";
const NOTO_MONO: &str = "/usr/share/fonts/google-noto-vf/NotoSansMono[wght].ttf";

/// Device-pixel sizes the UI corpus is checked at: a UI's 16, the same at
/// scale 2, and one in between that lands on no round number of design
/// units. The glyph ids must agree at all three and the positions must agree
/// with the font-unit answer scaled.
const SIZES: [f32; 3] = [16.0, 28.0, 32.0];

fn main() -> Result<()> {
    let only = std::env::args().nth(1);
    let gpu = Gpu::new()?;
    let mut failures = 0usize;

    if only.as_deref() != Some("--tests-only") {
        failures += ui_corpus(&gpu)?;
    }
    if only.as_deref() != Some("--ui-only") {
        failures += harfbuzz_corpus(&gpu)?;
    }

    println!();
    if failures == 0 {
        println!("every comparable run agrees with harfrust exactly");
        Ok(())
    } else {
        bail!("{failures} run(s) disagreed with harfrust");
    }
}

